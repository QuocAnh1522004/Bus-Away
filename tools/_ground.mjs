import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import { MeshoptDecoder } from 'meshoptimizer';
await MeshoptDecoder.ready;
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({ 'meshopt.decoder': MeshoptDecoder });
const doc = await io.read('src/assets/gen/models.glb');
const world = (node, p) => { const m = node.getWorldMatrix(); return [m[0]*p[0]+m[4]*p[1]+m[8]*p[2]+m[12], m[1]*p[0]+m[5]*p[1]+m[9]*p[2]+m[13], m[2]*p[0]+m[6]*p[1]+m[10]*p[2]+m[14]]; };
const g = doc.getRoot().listNodes().find(n => n.getName() === 'Ground_01');
const P = g.getMesh().listPrimitives()[0].getAttribute('POSITION');
const pts = []; for (let i = 0; i < P.getCount(); i++) pts.push(world(g, P.getElement(i, [])));
const raised = pts.filter(p => p[1] > 0.2 && p[2] > -1);
const xs = [...new Set(raised.map(p => +p[0].toFixed(2)))].sort((a,b)=>a-b);
console.log('raised curb verts near top edge: z range', Math.min(...raised.map(p=>p[2])).toFixed(3), Math.max(...raised.map(p=>p[2])).toFixed(3));
console.log('x values', xs.join(' '));
const r = doc.getRoot().listNodes().find(n => n.getName() === 'SplineMesh');
const RP = r.getMesh().listPrimitives()[0].getAttribute('POSITION');
let zmin = 1e9; const ends = [];
for (let i = 0; i < RP.getCount(); i++) { const p = world(r, RP.getElement(i, [])); if (p[2] < zmin) zmin = p[2]; if (p[2] < 1.75) ends.push(p); }
console.log('road zmin', zmin.toFixed(3));
const left = ends.filter(p=>p[0] < -2), right = ends.filter(p=>p[0] > -2);
for (const [n, e] of [['end A', left], ['end B', right]]) console.log(n, 'x', Math.min(...e.map(p=>p[0])).toFixed(3), '..', Math.max(...e.map(p=>p[0])).toFixed(3));
